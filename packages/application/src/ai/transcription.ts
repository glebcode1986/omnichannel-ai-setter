/**
 * Reading a customer's voice note (Issue #21).
 *
 * The port is deliberately the narrowest thing that can do the job: audio in, text out. There is no
 * conversation, no contact, no channel account and no recipient anywhere in the request — a transcriber
 * has no business knowing whose voice it is reading, and a port that carried that context would be one a
 * provider could be asked to make a decision with.
 *
 * **A transcript is evidence, not instruction.** It becomes the text of an `INBOUND` segment, which the
 * draft engine sanitizes and fences like every other piece of customer writing. Nothing about its origin
 * gives it authority, and the fact that a machine produced it from a recording makes it *less* certain
 * than typed text, not more.
 *
 * **Nothing here invents a confidence score.** The provider either reports one or it does not, and the
 * current recommended model reports none at all — so `confidence` is absent, and a caller that wants to
 * gate on certainty has to notice that rather than read a number somebody made up. `confidenceSource`
 * says where a present number came from, so an audit can tell a provider's own figure from a derived one.
 *
 * **A failure is a failure, never an empty transcript.** Every unhappy path returns a typed reason, and
 * the orchestration above turns it into a review item: a reply drafted against a recording nobody heard
 * is the invented content this whole path exists to prevent.
 */

/** The audio itself, with nothing about where it came from. */
export interface TranscriptionRequest {
  readonly audio: Uint8Array;
  /** The provider needs the container to identify the format; it is passed through unchanged. */
  readonly mimeType: string;
  /**
   * A filename for the provider's own format detection.
   *
   * Present because the providers say format metadata matters and an extension-bearing name is the
   * strongest hint available. It is generated by the caller, never a customer's own filename: a name that
   * travelled from a payload would put attacker-chosen text in a provider request.
   */
  readonly filename: string;
  /** Languages the audio might be in, as ISO-639-1 codes. A hint only; detection is the provider's. */
  readonly languageHints?: readonly string[];
  /** Domain words to bias the reading — a business name, a product. Never instructions. */
  readonly keywords?: readonly string[];
}

/** Where a confidence number came from, so a derived one is never mistaken for the provider's own. */
export type ConfidenceSource = "PROVIDER" | "DERIVED";

export interface Transcript {
  readonly text: string;
  /** Who read it, and which model actually ran — not the alias that was requested. */
  readonly provider: string;
  readonly model: string;
  /**
   * The provider's own revision marker for that model, when it publishes one.
   *
   * Separate from `model` because a model name is an alias that can start meaning something else, and a
   * transcript re-read in six months has to be attributable to what actually produced it.
   */
  readonly modelRevision?: string;
  /** ISO-639-1 where the provider gives one. Absent when it could not detect a language. */
  readonly language?: string;
  /** Absent when the provider reports none. Never invented, and never defaulted to 1. */
  readonly confidence?: number;
  readonly confidenceSource?: ConfidenceSource;
  readonly durationSeconds?: number;
  readonly providerRequestId?: string;
  readonly latencyMs: number;
}

/**
 * Why a recording could not be read. Each one is a different sentence to an operator, and each one is a
 * refusal rather than a transcript.
 */
export type TranscriptionFailure =
  /** The deployment has no transcriber configured. A supported configuration, not a fault. */
  | "NOT_CONFIGURED"
  /** The provider will not read this container or codec. The answer cannot change on a retry. */
  | "UNSUPPORTED_AUDIO"
  /** Larger than the provider accepts. Refused locally, because no provider publishes a status for it. */
  | "TOO_LARGE"
  /** The provider answered, and what it said could not be read as a transcription. */
  | "MALFORMED_RESULT"
  /** The provider answered with no words at all, which is not the same as a transcript of silence. */
  | "EMPTY_RESULT"
  /** The provider refused for a reason that will not change by asking again. */
  | "PROVIDER_REJECTED"
  /** Throttled, overloaded or unreachable. Safe to retry: nothing was produced. */
  | "UNAVAILABLE"
  /** Quota or billing. Technically a refusal, and retrying it is how a bill becomes a loop. */
  | "QUOTA_EXHAUSTED";

export type TranscriptionOutcome =
  | { readonly ok: true; readonly transcript: Transcript }
  | {
      readonly ok: false;
      readonly reason: TranscriptionFailure;
      /** The provider's own code, for the audit. Never its prose, which can quote the recording. */
      readonly code?: string;
      /** Set when the provider asked us to wait, so a retry honours it rather than guessing. */
      readonly retryAfterSeconds?: number;
    };

/** Implemented in `packages/ai`; the composition roots wire it in. */
export interface TranscriptionProvider {
  /** The provider and model this instance will report, so a caller can record them before it runs. */
  readonly provider: string;
  readonly model: string;
  transcribe(request: TranscriptionRequest): Promise<TranscriptionOutcome>;
}

/**
 * Whether asking again could produce a different answer.
 *
 * The distinction the queue needs: an unsupported container is the same refusal every time and retrying
 * it only delays the review item a person is waiting for, while a throttled provider is worth another
 * attempt. Quota is deliberately *not* retryable — retrying a spend limit is how a bill becomes a loop.
 */
export function transcriptionRetryable(reason: TranscriptionFailure): boolean {
  return reason === "UNAVAILABLE";
}

export class TranscriptionUnavailableError extends Error {
  constructor(reason: string) {
    // Reasons name the class of failure only: a provider message can quote the recording.
    super(`transcription unavailable: ${reason}`);
    this.name = "TranscriptionUnavailableError";
  }
}
