/**
 * The golden suite.
 *
 * Every case states, in its `intent`, what it is protecting — because a case whose purpose nobody remembers
 * is a case that gets deleted the first time it is inconvenient.
 *
 * None of this is customer data. The conversations are written for the suite, and the businesses in them
 * do not exist.
 *
 * ## Adding a case
 *
 * Add an entry here with an `id` nothing else uses, the category it belongs to, the conversation, whatever
 * knowledge or style the business would actually have, and the model's answer as `fixtureReply`. Then say
 * what must be true in `assertions` — those are checked exactly — and, only if the case is about wording,
 * what a good answer looks like in `quality`. Never put a policy expectation in `quality`: a decision that
 * can be graded away is not a decision.
 */
