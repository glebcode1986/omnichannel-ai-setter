import { DomainValidationError } from "./errors";

declare const brand: unique symbol;

/** A string identifier that cannot be mixed up with identifiers of other entities at compile time. */
export type Id<Entity extends string> = string & { readonly [brand]: Entity };

export type WorkspaceId = Id<"Workspace">;
export type UserId = Id<"User">;
export type ChannelAccountId = Id<"ChannelAccount">;
export type ContactId = Id<"Contact">;
export type ContactIdentityId = Id<"ContactIdentity">;
export type ConversationId = Id<"Conversation">;
export type MessageId = Id<"Message">;
export type AiDraftId = Id<"AiDraft">;
export type DeliveryJobId = Id<"DeliveryJob">;
export type AutomationPolicyId = Id<"AutomationPolicy">;
/** Idempotency/audit identity of one logical outbound action, generated by the application. */
export type OperationId = Id<"Operation">;
/** End-to-end correlation identifier spanning webhook, persistence, queue and delivery. */
export type CorrelationId = Id<"Correlation">;
/** Opaque reference to encrypted channel credentials; never the secret itself. */
export type CredentialReference = Id<"CredentialReference">;

export const MAX_ID_LENGTH = 255;

/** Identifiers are non-empty, at most 255 characters and contain no whitespace or control characters. */
export function isValidIdentifier(value: unknown): value is string {
  return typeof value === "string" && value.length > 0 && value.length <= MAX_ID_LENGTH && !/[\s\p{Cc}]/u.test(value);
}

function toId<Entity extends string>(field: string) {
  return (value: string): Id<Entity> => {
    if (!isValidIdentifier(value)) {
      throw new DomainValidationError(field, `must be a non-empty identifier of at most ${MAX_ID_LENGTH} characters without whitespace`);
    }
    return value as Id<Entity>;
  };
}

export const toWorkspaceId = toId<"Workspace">("workspaceId");
export const toUserId = toId<"User">("userId");
export const toChannelAccountId = toId<"ChannelAccount">("channelAccountId");
export const toContactId = toId<"Contact">("contactId");
export const toContactIdentityId = toId<"ContactIdentity">("contactIdentityId");
export const toConversationId = toId<"Conversation">("conversationId");
export const toMessageId = toId<"Message">("messageId");
export const toAiDraftId = toId<"AiDraft">("aiDraftId");
export const toDeliveryJobId = toId<"DeliveryJob">("deliveryJobId");
export const toAutomationPolicyId = toId<"AutomationPolicy">("automationPolicyId");
export const toOperationId = toId<"Operation">("operationId");
export const toCorrelationId = toId<"Correlation">("correlationId");
export const toCredentialReference = toId<"CredentialReference">("credentialReference");
